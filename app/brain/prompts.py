def user_prompt(topic: str, content_type: str) -> str:
    schema = SCHEMAS[content_type].model_json_schema()
    return f"""موضوع: {topic}

{_TYPE_GUIDE[content_type]}

product_keywords: چند کلیدواژه‌ی محصول مرتبط با موضوع (برای پیشنهاد محصول از فروشگاه).

اسکیمای JSON خروجی:
{json.dumps(schema, ensure_ascii=False)}
"""


def repair_prompt(errors: str) -> str:
    return f"""خروجی قبلی معتبر نبود. خطاها:
{errors}

همان محتوا را اصلاح کن و فقط JSON معتبر و کامل مطابق اسکیما برگردان."""
